#!/usr/bin/env python3
"""gen_chain_fixture.py -- deterministically generate an N-step "chain" bug
fixture, used to measure how deep a transaction SEQUENCE ForkSploit can reach
(BLOKATORJI.md B1).

The generated contract `Chain` breaks the declared invariant
`value() <= 1` ONLY after `depth` sequential transactions:

    step0()            -> stage = 1
    step1()  require(stage == 1); stage = 2
    ...
    step{depth-1}()    require(stage == depth-1); stage = depth
    fire()   require(stage == depth); value = 2      <-- breaks value() <= 1

No single transaction can do it: every step reverts until the previous one has
run, and fire() reverts until all of them have. Only the full sequence does.

Usage:
    python onchain_scripts/gen_chain_fixture.py <depth> <out_dir>

Writes main.sol / main.abi / main.bin / invariants.json into <out_dir>, then
measure with e.g.:

    forksploit evm -t '<out_dir>/*' -f -d invariant \\
        --invariants <out_dir>/invariants.json -w /tmp/chain<depth>
"""
import json
import os
import sys

import solcx


def build_source(depth):
    funcs = ["function step0() public { stage = 1; }"]
    for i in range(1, depth):
        funcs.append(
            f'function step{i}() public {{ require(stage == {i}, "x"); stage = {i + 1}; }}'
        )
    funcs.append(
        f'function fire() public {{ require(stage == {depth}, "x"); value = 2; }}'
    )
    body = "\n    ".join(funcs)
    return f"""// SPDX-License-Identifier: UNLICENSED
pragma solidity ^0.8.19;

// Generated by onchain_scripts/gen_chain_fixture.py (depth={depth}).
// The declared invariant value() <= 1 is broken ONLY by the full sequence of
// {depth} setup transactions followed by fire().
contract Chain {{
    uint256 public stage;
    uint256 public value;

    {body}
}}
"""


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    depth = int(sys.argv[1])
    out_dir = sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)

    src = build_source(depth)
    out = solcx.compile_source(src, output_values=["abi", "bin"], solc_version="0.8.19")
    key = next(k for k in out if k.endswith(":Chain"))

    with open(os.path.join(out_dir, "main.sol"), "w") as f:
        f.write(src)
    with open(os.path.join(out_dir, "main.abi"), "w") as f:
        json.dump(out[key]["abi"], f)
    with open(os.path.join(out_dir, "main.bin"), "w") as f:
        f.write(out[key]["bin"])
    with open(os.path.join(out_dir, "invariants.json"), "w") as f:
        json.dump(
            {
                "invariants": [
                    {
                        "name": "value stays within cap",
                        "op": "le",
                        "lhs": {"call": {"sig": "value()"}},
                        "rhs": {"literal": "1"},
                    }
                ]
            },
            f,
        )
    print(f"built {out_dir}: needs {depth} sequential txs to fire")


if __name__ == "__main__":
    main()
